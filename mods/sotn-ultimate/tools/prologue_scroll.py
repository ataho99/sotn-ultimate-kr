"""The prologue scroll's text per dub (ST0, after the Dracula fight;
src/st/st0/3101C_psx.c draws it a line at a time with the BIOS font).

  PS1 dub: the retail script (src/st/st0/prologue_cutscene_script.h)
  PSP dub: the PSP's English scroll (the UMD's PSPBIN/st0.bin), the text as
           it is, re-centred for the PS1 font (the PSP's x offsets are for its
           own renderer)
  JP dub:  the English retranslation (tools/retrans/prologue_scroll.json)

Each copy is a retail-format script (line, then 1 = next line / 2 = next
paragraph, followed by the next line's x; 0 at the end) after one byte: the
first line's x (retail's is fixed at 0x16 in func_801B101C). x = (110 -
width) / 2 in VRAM words, width = 3 a letter, 2 a space, as retail's
(2 * x + width = 108-111 on every US line); a line holds 116.

  prologue_scroll.py         write src/st/st0/mod_prologue_scroll.h (the JP
                             copy in full, the PSP one as a zero-filled array)
                             and build/us/psp_script/prologue_tokens.json
                             (the PSP lines, which the release blanks:
                             builder/node/psp_text_tokens.py)
  prologue_scroll.py --off   the same without the PSP copy (MOD_PSP_DUB=0)
  prologue_scroll.py --apply fill the PSP copy in build/us/ST0.BIN
  prologue_scroll.py --check only check that

The music: src/st/st0/prologue_scroll.c plays MU_MOD_PROLOGUE_JP (the
Saturn's SD21, Moonlight Nocturne with the Japanese narration) or
MU_MOD_PROLOGUE_EN (the PSP's English narration, PS_OP_NA.at3) by dub
(mods/sotn-ultimate/tools/gen_saturn_music.py)."""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
PSP_ST0 = os.path.join(ROOT, "disks/psp/PSPBIN/st0.bin")
RT_JSON = os.path.join(os.path.dirname(os.path.abspath(__file__)), "retrans/prologue_scroll.json")
HEADER = os.path.join(ROOT, "src/st/st0/mod_prologue_scroll.h")
TOKENS = os.path.join(ROOT, "build/us/psp_script/prologue_tokens.json")
BIN = os.path.join(ROOT, "build/us/ST0.BIN")
MAP = os.path.join(ROOT, "build/us/stst0.map")
BASE = 0x80180000
CENTRE = 110
MAX_WIDTH = 116
# characters 3101C_psx.c func_801B11E8 maps to the BIOS font: letters,
# digits, , . ' and (the mod's case) -; others (? ! : ...) land on wrong
# codes through its 'Ａ' - 'A' + ch arithmetic
CHARS = re.compile(r"^[A-Za-z0-9 ,.'\-]*$")


def width(line):
    return sum(2 if c == " " else 3 for c in line)


def x_of(line, where):
    assert CHARS.match(line), "%s: %r has a character the scroll cannot draw" % (where, line)
    w = width(line)
    assert w <= MAX_WIDTH, "%s: %r is %d wide (max %d)" % (where, line, w, MAX_WIDTH)
    return max(0, (CENTRE - w) // 2)


def script(paragraphs, where):
    """[first x] + the retail-format script"""
    lines = [(line, k == len(p) - 1) for p in paragraphs for k, line in enumerate(p)]
    out = bytearray([x_of(lines[0][0], where)])
    for i, (line, last) in enumerate(lines):
        out += line.encode("ascii")
        if i + 1 < len(lines):
            out += bytes([2 if last else 1, x_of(lines[i + 1][0], where)])
    return bytes(out + b"\0")


def psp_paragraphs():
    d = open(PSP_ST0, "rb").read()
    at = d.find(b"Count Dracula had risen")
    assert at >= 0, "PSPBIN/st0.bin: no English prologue scroll"
    raw = d[at:d.index(b"\0", at)]
    paras, cur, i, line = [], [], 0, b""
    while i < len(raw):
        c = raw[i]
        if c in (1, 2):
            cur.append(line.decode("ascii"))
            line = b""
            if c == 2:
                paras.append(cur)
                cur = []
            i += 2
            continue
        line += bytes([c])
        i += 1
    cur.append(line.decode("ascii"))
    paras.append(cur)
    return paras


def jp_paragraphs():
    return json.load(open(RT_JSON, encoding="utf-8"))["paragraphs"]


def c_bytes(b):
    rows = [", ".join("0x%02X" % x for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return "\n".join("    " + r + "," for r in rows)


def generate(off):
    jp = script(jp_paragraphs(), "retranslation")
    psp = None if off else script(psp_paragraphs(), "PSP scroll")
    s = ("// Generated by mods/sotn-ultimate/tools/prologue_scroll.py, do not edit\n"
         "// The prologue scroll's text per dub (3101C_psx.c func_801B1298): the\n"
         "// JP dub's English retranslation (Gemini, throughhim413, Tom; used with\n"
         "// permission) and the PSP dub's English scroll; byte 0 = the first\n"
         "// line's x, then a retail-format script\n"
         "#if defined(MOD_SATURN) && defined(VERSION_US)\n"
         "#define MOD_PROLOGUE_SCROLL\n"
         "static const u8 g_ModScrollJp[%d] = {\n%s\n};\n" % (len(jp), c_bytes(jp)))
    if psp:
        s += ("#define MOD_PROLOGUE_SCROLL_PSP\n"
              "// filled from the UMD by prologue_scroll.py --apply\n"
              "u8 g_ModScrollPsp[%d] __attribute__((section(\".rodata\"))) = {0};\n" % len(psp))
    s += ("static u16 g_ModScrollX; // the first line's x\n"
          "static u8* ModPrologueScript(u8* script) {\n"
          "    const u8* s = NULL;\n"
          "\n"
          "    if (MOD_JP_DUB_ON()) {\n"
          "        s = g_ModScrollJp;\n")
    if psp:
        s += ("    } else if (MOD_PSP_DUB_ON() && g_ModScrollPsp[1]) {\n"
              "        s = g_ModScrollPsp;\n")
    s += ("    }\n"
          "    if (!s) {\n"
          "        g_ModScrollX = 0x16; // retail's (func_801B101C)\n"
          "        return script;\n"
          "    }\n"
          "    g_ModScrollX = s[0];\n"
          "    return (u8*)s + 1;\n"
          "}\n"
          "#endif\n")
    old = open(HEADER).read() if os.path.exists(HEADER) else None
    if old != s:
        open(HEADER, "w").write(s)
    os.makedirs(os.path.dirname(TOKENS), exist_ok=True)
    lines = [] if off else [line for p in psp_paragraphs() for line in p]
    json.dump({"file": "ST/ST0/ST0.BIN", "tokens": lines,
               "psp": psp.hex() if psp else None}, open(TOKENS, "w"))
    print("prologue scroll: JP %d bytes%s" % (len(jp), "" if off else ", PSP %d bytes" % len(psp)))


def apply(check):
    plan = json.load(open(TOKENS))
    if not plan["psp"]:
        return
    psp = bytes.fromhex(plan["psp"])
    m = re.search(r"0x([0-9a-f]+)\s+g_ModScrollPsp\n", open(MAP).read())
    assert m, "stst0.map: g_ModScrollPsp not linked (mod_prologue_scroll.h?)"
    o = int(m[1], 16) - BASE
    b = bytearray(open(BIN, "rb").read())
    if bytes(b[o:o + len(psp)]) == psp:
        print("prologue scroll: PSP copy in place")
        return
    if check:
        sys.exit("prologue_scroll: build/us/ST0.BIN at 0x%X: the PSP copy is not filled" % o)
    assert not any(b[o:o + len(psp)]), "ST0.BIN at 0x%X: not the empty PSP copy" % o
    b[o:o + len(psp)] = psp
    open(BIN, "wb").write(b)
    print("prologue scroll: PSP copy filled (build/us/ST0.BIN)")


if __name__ == "__main__":
    if "--apply" in sys.argv or "--check" in sys.argv:
        apply("--check" in sys.argv)
    else:
        generate("--off" in sys.argv)
