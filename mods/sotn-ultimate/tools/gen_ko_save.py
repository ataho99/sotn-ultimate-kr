#!/usr/bin/env python3
# gen_ko_save.py -- Korean strings of the save room (src/dra/62DEC.c func_800F9D88 boxes) -> src/dra/gen/us/ko_save_str.h
# Input : 한글작업/번역/번역_저장문구.tsv (키, 영문, 일판, 한글)
# Output: #define KS_xxx "..." : Hangul/digits/punctuation as glyph codes (F0xx big endian: Hangul from the glyph map,
#         ASCII from KO_ENGTAB = MGalmuri12 cells), space 0x20. Pairs are emitted as separate literals ("\xF2" "\x1C")
#         so no hex escape swallows the next character. NO plain ASCII letter/digit is emitted: func_800F99B8 turns those into
#         fullwidth SJIS = console BIOS Kanji ROM (the grey text), so every glyph must have an MGalmuri12 cell (fail closed).
import io
from ko_paths import KO_WK  # noqa: E402
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ko_font_profile as FP  # noqa: E402

WK = (KO_WK + "/")
P4 = WK + "P4시험/"
TSV = WK + "번역/번역_저장문구.tsv"
REPO = os.environ.get("SOTN_KR", os.getcwd())
OUT = os.path.join(REPO, "src/dra/gen/us/ko_save_str.h")


Q = chr(34)
BS = chr(92)


def main():
    mp = {}
    for ln in io.open(P4 + FP.P["map_name"], encoding="utf-8"):
        q = ln.rstrip(chr(10)).split(chr(9))
        if len(q) >= 2 and q[1].startswith("0x") and len(q[0]) == 1:
            mp[q[0]] = int(q[1], 16)
    eng = struct.unpack("<94H", open(P4 + "ko_engtab_253.bin", "rb").read())
    rows = [l.rstrip(chr(10)).split(chr(9)) for l in io.open(TSV, encoding="utf-8")][1:]
    out = ["// generated by gen_ko_save.py from 번역_저장문구.tsv -- do not edit"]
    missing = []
    for key, en, jp, ko in rows:
        parts = []
        for ch in ko:
            if ch == " ":
                parts.append(Q + BS + "x20" + Q)
                continue
            code = mp.get(ch) if ord(ch) > 127 else (eng[ord(ch) - 0x21] or None)
            if not code:
                missing.append(ch)
                continue
            parts.append(Q + BS + "x%02X" % (code >> 8) + Q + " " + Q + BS + "x%02X" % (code & 255) + Q)
        out.append("#define %s %s" % (key, " ".join(parts) if parts else '""'))
    assert not missing, ("no MGalmuri12 cell for", "".join(sorted(set(missing))))
    open(OUT, "w", encoding="utf-8").write(chr(10).join(out) + chr(10))
    print("ko_save_str.h: %d strings, every glyph has a cell (BIOS font glyphs: 0)" % len(rows))


if __name__ == "__main__":
    sys.exit(main())
