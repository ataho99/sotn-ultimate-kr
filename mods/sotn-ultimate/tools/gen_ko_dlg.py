# gen_ko_dlg.py -- v13 cutscene dialogue KO bake (trial builds only).
# 입력: 한글작업/번역/번역_v13_통합.tsv (분류=대사) + P4시험/ko_glyph_map_*.tsv (프로필 map_name)
# 출력: <stage>/gen/cutscene_ko.h (무시됨, 빌드 생성물. 대사 파일은 추출기가
#   매 빌드 다시 만드는 생성물이라 손 주입 금지 -- 인계문서 §2-2).
#   행마다 KO 바이트열 1개 (ASCII 1B 그대로, 한글 F0xx 2B raw, `/` -> `\n`
#   유지(후단에서 LINE_BREAK으로), `…` -> `...`). `_S()` 사용 금지
#   (sotn_str가 한글을 조용히 버림) -- raw 바이트만.
# 배선(다음 턴): 각 스테이지 SetCutsceneScript에 MOD_KO 분기로 KO 표 선택.
#   표는 rodata append라 .data 불변 (check_stage_data) -- ST0 프롤로그 선례
#   (46fa2bf73, data 32418워드 이동 FAIL) 때문.
import io
from ko_paths import KO_WK, KO_REPO  # noqa: E402
import os
import re
import sys

REPO = os.environ.get("SOTN_KR", KO_REPO)
TSV = (KO_WK + "/검수/번역_v14.tsv")
MAP = (KO_WK + "/P4시험/") + __import__("ko_font_profile").P["map_name"] + ""

# TSV 키 접두 -> (스테이지 디렉토리, 테이블 태그)
STAGE = {
    "no3_death": ("st/no3", "NO3"),
    "cen_maria": ("st/cen", "CEN"),
    "lib_librarian": ("st/lib", "LIB"),
    "nz0_slogra_gaibon": ("st/nz0", "NZ0"),
    "sel_ending": ("st/sel", "SEL"),
    "top_maria_richter": ("st/top", "TOP"),
    "st0_richter_dracula": ("st/st0", "ST0_DLG"),
    "st0_psp_opening": ("st/st0", "ST0_OPEN"),
    "no4_ferryman_left": ("st/no4", "NO4_L"),
    "no4_ferryman_right": ("st/no4", "NO4_R"),
    "rcen_shaft": ("st/rcen", "RCEN"),
    "dai_huntinggirl": ("st/dai", "DAI"),
    "dre_succubus": ("st/dre", "DRE"),
    "prologue_us_psx": ("st/st0", "ST0_PROLOGUE_US"),
    "prologue_psp_en": ("st/st0", "ST0_PROLOGUE_PSP"),
    "mod_maria_boss_data.h:g_MbScriptPre": ("boss/mar", "MAR_PRE"),
    "mod_maria_boss_data.h:g_MbScriptPost": ("boss/mar", "MAR_POST"),
}


def load_map():
    mp = {}
    for line in io.open(MAP, encoding="utf-8"):
        p = line.rstrip("\n").split("\t")
        if len(p) >= 2 and len(p[0]) == 1 and p[1].startswith("0x"):
            mp[p[0]] = int(p[1], 16)
    assert len(mp) >= 700, len(mp)  # glyph-map size sanity check
    return mp


def enc(s, mp, key):
    out = bytearray()
    for ch in s:
        o = ord(ch)
        if o < 128:
            out.append(o)
        elif ch == "…":
            out.extend(b"\xF1\xA0")  # v12f cell F1A0 (12px ellipsis)
        else:
            assert ch in mp, (key, repr(ch))
            code = mp[ch]
            assert 0xF040 <= code <= 0xF375, (key, repr(ch), hex(code))
            out.append(code >> 8)
            out.append(code & 0xFF)
    return bytes(out)


def main():
    mp = load_map()
    rows = [l.rstrip("\n").split("\t")
            for l in io.open(TSV, encoding="utf-8")]
    head = rows[0]
    ki, ci, ei, ti = head.index("키"), head.index("분류"), head.index("EN"), [i for i, x in enumerate(head) if x.startswith("번역")][0]
    per = {}
    for r in rows[1:]:
        if len(r) <= ti or r[ci] != "대사":
            continue
        key = r[ki]
        pre = key.rsplit(":", 1)[0]
        if pre in ("mod_maria_boss_data.h",) or re.match(r"(bo|rbo)\d+_|mar_", pre):
            continue  # 보스 스크립트 행은 gen_ko_splice(--apply-boss)/gen_ko_mar 담당
        assert pre in STAGE, key
        t = r[ti].replace("…", "...").replace("\\n", "/")
        # 9 dots -> two ellipsis cells, 3 dots -> one (same rule as
        # gen_ko_splice.py ell())
        t = t.replace(".........", "……").replace("...", "…")
        per.setdefault(pre, []).append((key, enc(t, mp, key)))
    total = 0
    for pre, items in sorted(per.items()):
        d, tag = STAGE[pre]
        gendir = os.path.join(REPO, "src", d, "gen")
        os.makedirs(gendir, exist_ok=True)
        fn = "cutscene_ko_%s.h" % re.sub(r"[^0-9A-Za-z]+", "_", pre).lower()
        dst = os.path.join(gendir, fn)
        with io.open(dst, "w", encoding="utf-8") as f:
            f.write("// @generated by mods/sotn-ultimate/tools/gen_ko_dlg.py -- DO NOT EDIT\n")
            f.write("// stage %s (%d lines)\n" % (tag, len(items)))
            f.write("#pragma once\n")
            for i, (key, esc) in enumerate(items):
                f.write("// %s\nstatic const u8 ko_dlg_%s_%d[] = {%s};\n" % (key, tag, i, ",".join("0x%02X" % b for b in esc)))
                f.write("#define KO_DLG_%s_%d_LEN %d\n" % (tag, i, len(esc)))
            f.write("#define KO_DLG_%s_COUNT %d\n" % (tag, len(items)))
        print("%s: %d lines -> %s" % (tag, len(items), dst))
        total += len(items)
    print("TOTAL %d lines" % total)


if __name__ == "__main__":
    sys.exit(main())
