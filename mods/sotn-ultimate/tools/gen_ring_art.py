"""Ring art for the transformation ring (new resident area): the "release" icon (a round badge with a person), a 4 bit 16x16 equip-icon slot image
plus its palette (5 colours used, 16 entries).
Output: mods/sotn-ultimate/src/easy/ring_art.h (static const data, linked into the new area with r1_easy.c).
"""
import os

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))


def pack(rows):  # 16 rows of 16 px -> 128 B, low nibble = left pixel
    b = bytearray()
    for r in rows:
        for x in range(0, 16, 2):
            b.append(r[x] | (r[x + 1] << 4))
    return bytes(b)


# outline 1, fill 2, light rim 4, white person 3
ic = [[0] * 16 for _ in range(16)]
cx = cy = 7.5
for y in range(16):
    for x in range(16):
        d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
        if d <= 7.6:
            ic[y][x] = 1
        if d <= 6.4:
            ic[y][x] = 2
        if 5.4 <= d <= 6.4 and y < 8:
            ic[y][x] = 4
for y in range(16):
    for x in range(16):
        if ((x - 7.5) ** 2 + (y - 5.2) ** 2) ** 0.5 <= 2.3:
            ic[y][x] = 3
        if y >= 8 and abs(x - 7.5) <= 2 + (y - 8) * 0.9 and ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5 <= 6.0:
            ic[y][x] = 3
rel = pack(ic)


def c555(r, g, b):
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


palrel = [0, c555(40, 48, 70), c555(95, 115, 150), c555(235, 240, 250), c555(150, 170, 200)] + [0] * 11
lines = ["// generated by tools/gen_ring_art.py (do not edit): the transformation ring's release icon (4 bit 16x16 slot image + its palette)"]
lines.append('static const u8 g_RingRel[128] = {')
for i in range(0, 128, 16):
    lines.append('    ' + ', '.join('0x%02X' % v for v in rel[i:i + 16]) + ',')
lines.append('};')
lines.append('static const u16 g_RingPalRel[16] = {%s};' % ', '.join('0x%04X' % x for x in palrel))
open(os.path.join(root, 'mods/sotn-ultimate/src/easy/ring_art.h'), 'w').write('\n'.join(lines) + '\n')
print('ring_art.h written: release icon 128 B + 5 colours')
