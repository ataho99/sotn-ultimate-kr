# gen_ko_shop.py -- KO: the Librarian shop's hard-coded English tables (src/st/lib/e_shop.c): label words
# (Number / Equipped / Not equipped), the Jewel of Open / document names (Castle Map, Magic Scroll 1-5) and the
# document descriptions.
# Input : 번역/번역_상점.tsv (키, 분류, 영문, 한글, 비고)
# Output: src/st/lib/gen/ko_shop_str.h  (#define KO_SHOP_<KEY> "...")  -- generated, not tracked
# Two encodings, as the shop's own two text paths read them (NOT the relic menu's ShowText format, which uses
# space 20 and NUL end and cannot be drawn by func_us_801B1064):
#   kind "이름 형식" (func_us_801B1064): Hangul = 12px glyph-map code pair (F0xx..), space = 00, other ASCII = ch - 0x20,
#                     end FF 00  (the same as equipment names, gen_ko_equip.py enc_name)
#   kind "설명 형식" (func_us_801B0C40, the description box): Hangul = glyph code pair, space = 20, end 00; no ASCII
#                     letters/digits/punctuation (the retail font path widens them: write words only)
# Fail closed: every Hangul needs a glyph-map code (<= 0xF3F7); description rows may not hold ASCII non-space;
# the Jewel of Open name must equal the relic menu's name (번역_v14.tsv config_us.h:g_RelicDefs:16:name).
import io
import os
import sys

from ko_paths import KO_WK, KO_REPO  # noqa: E402
import ko_font_profile as FP  # noqa: E402

NL = chr(10)
TAB = chr(9)
BS = chr(92)
REPO = os.environ.get("SOTN_KR", KO_REPO)
TSV = os.path.join(KO_WK, "번역", "번역_상점.tsv")
OUT = os.path.join(REPO, "src", "st", "lib", "gen", "ko_shop_str.h")
P4 = KO_WK + "/P4시험/"


def is_h(c):
    return "가" <= c <= "힣"


def main():
    mp = {}
    for ln in io.open(P4 + FP.P["map_name"], encoding="utf-8"):
        q = ln.rstrip(NL).split(TAB)
        if len(q) >= 2 and len(q[0]) == 1 and q[1].startswith("0x"):
            mp[q[0]] = int(q[1], 16)
    relic16 = None
    for ln in io.open(os.path.join(KO_WK, "검수", "번역_v14.tsv"), encoding="utf-8"):
        q = ln.rstrip(NL).split(TAB)
        if len(q) > 3 and q[0] == "config_us.h:g_RelicDefs:16:name":
            relic16 = q[3]
    assert relic16, "relic 16 name not found in 번역_v14.tsv"
    out = ["// generated by gen_ko_shop.py from 번역_상점.tsv -- do not edit"]
    n = 0
    for ln in io.open(TSV, encoding="utf-8").read().split(NL)[1:]:
        q = ln.split(TAB)
        if len(q) < 4 or not q[0].startswith("shop:"):
            continue
        key, kind, ko = q[0][5:], q[1], q[3]
        if key == "relic0":
            assert ko == relic16, ("shop Jewel of Open name differs from the relic menu name", ko, relic16)
        is_name = "이름" in kind
        b = bytearray()
        for ch in ko:
            if ch == " ":
                b.append(0x00 if is_name else 0x20)
            elif is_h(ch):
                assert ch in mp, ("no glyph code", ch, key)
                assert 0xF040 <= mp[ch] <= 0xF3F7, (ch, hex(mp[ch]), key)
                b += bytes([mp[ch] >> 8, mp[ch] & 0xFF])
            else:
                assert is_name and 0x20 < ord(ch) < 0x7F, ("char not allowed in this kind", ch, key, kind)
                b.append(ord(ch) - 0x20)
        b += bytes([0xFF, 0x00]) if is_name else bytes([0x00])
        esc = "".join(BS + "x%02X" % x for x in b)
        out.append("#define KO_SHOP_%s %s%s%s" % (key.upper(), chr(34), esc, chr(34)))
        n += 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    io.open(OUT, "w", encoding="utf-8", newline="").write(NL.join(out) + NL)
    print("ko_shop_str.h: %d strings, every glyph has a code; Jewel of Open name = relic menu name" % n)


if __name__ == "__main__":
    sys.exit(main())
